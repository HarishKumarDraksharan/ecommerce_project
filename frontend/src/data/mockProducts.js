// ── Helper selectors ──────────────────────────────────────────────────────

export function getFeaturedProducts(limit = 8) {
  return MOCK_PRODUCTS.filter(p => p.featured).slice(0, limit)
}

export function getBestSellers(limit = 8) {
  return [...MOCK_PRODUCTS].sort((a, b) => b.totalSold - a.totalSold).slice(0, limit)
}

export function getNewArrivals(limit = 8) {
  return [...MOCK_PRODUCTS].sort((a, b) => new Date(b.createdAt) - new Date(a.createdAt)).slice(0, limit)
}

export function getByCategory(slug, limit = 20) {
  return MOCK_PRODUCTS.filter(p => p.categorySlug === slug).slice(0, limit)
}

export function searchProducts(query) {
  const q = query.toLowerCase()
  return MOCK_PRODUCTS.filter(p =>
    p.name.toLowerCase().includes(q) ||
    p.brand.toLowerCase().includes(q) ||
    p.category.toLowerCase().includes(q) ||
    (p.tags || []).some(t => t.includes(q))
  )
}

export function sortProducts(products, sortBy, sortDir = 'desc') {
  return [...products].sort((a, b) => {
    let va = a[sortBy], vb = b[sortBy]
    if (typeof va === 'string') { va = new Date(va); vb = new Date(vb) }
    return sortDir === 'asc' ? va - vb : vb - va
  })
}

export function filterProducts(products, { category, brand, minPrice, maxPrice, rating, featured, bestseller }) {
  return products.filter(p => {
    if (category && p.categorySlug !== category) return false
    if (brand    && p.brand.toLowerCase() !== brand.toLowerCase()) return false
    if (minPrice && p.price < Number(minPrice)) return false
    if (maxPrice && p.price > Number(maxPrice)) return false
    if (rating   && (p.avgRating || p.rating) < Number(rating)) return false
    if (featured === 'true' && !p.featured) return false
    if (bestseller === 'true' && !(p.bestSeller || p.bestseller)) return false
    return true
  })
}

// Paginate an array
export function paginate(items, page = 0, size = 12) {
  const start = page * size
  const slice = items.slice(start, start + size)
  return {
    content:       slice,
    totalElements: items.length,
    totalPages:    Math.ceil(items.length / size),
    currentPage:   page,
    size,
  }
}
